-- The tables SubFlow had before the migrations in this folder began.
-- Later scripts build on them: V1 references subscriptions, and V5 adds
-- the unique e-mail index and the status and date checks.
CREATE TABLE customers (
  id    BIGINT       PRIMARY KEY,
  email VARCHAR(254) NOT NULL
);

CREATE TABLE subscriptions (
  id          BIGINT      PRIMARY KEY,
  customer_id BIGINT      NOT NULL REFERENCES customers (id),
  plan        VARCHAR(16) NOT NULL,
  cycle       VARCHAR(16) NOT NULL,
  status      VARCHAR(16) NOT NULL,
  start_date  DATE        NOT NULL,
  end_date    DATE
);

CREATE TABLE invoices (
  id              BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subscription_id BIGINT        NOT NULL REFERENCES subscriptions (id),
  customer_email  VARCHAR(254)  NOT NULL,
  total           DECIMAL(12,2) NOT NULL,
  currency        CHAR(3)       NOT NULL,
  issued_on       DATE          NOT NULL
);
